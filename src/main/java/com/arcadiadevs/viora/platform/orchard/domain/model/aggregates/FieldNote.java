package com.arcadiadevs.viora.platform.orchard.domain.model.aggregates;

import com.arcadiadevs.viora.platform.orchard.domain.model.valueobjects.FieldNoteId;
import com.arcadiadevs.viora.platform.orchard.domain.model.valueobjects.FieldNotePhoto;
import com.arcadiadevs.viora.platform.orchard.domain.model.valueobjects.FieldNoteText;
import com.arcadiadevs.viora.platform.orchard.domain.model.valueobjects.FieldNoteType;
import com.arcadiadevs.viora.platform.orchard.domain.model.valueobjects.PlotId;
import com.arcadiadevs.viora.platform.orchard.domain.model.valueobjects.ProducerId;

import java.time.Instant;
import java.time.LocalDate;

/**
 * A note the producer writes in the logbook about one plot (P75): irrigation, pruning, fertilization, pests or
 * anything else, with an optional photo. The text never changes once stored; only the photo can be attached or
 * replaced, because the phone uploads it after the note when the connection allows.
 */
public final class FieldNote {

    private final FieldNoteSnapshot snapshot;

    private FieldNote(FieldNoteSnapshot snapshot) {
        if (snapshot == null) {
            throw new IllegalArgumentException("orchard.field_note.content.invalid");
        }
        this.snapshot = snapshot;
    }

    /**
     * Rebuilds a stored note.
     *
     * @param snapshot stored state
     * @return the note
     */
    public static FieldNote reconstitute(FieldNoteSnapshot snapshot) {
        return new FieldNote(snapshot);
    }

    /**
     * Writes a new note.
     *
     * @param id         identity generated by the phone
     * @param plotId     plot the note is about
     * @param producerId owner of the plot
     * @param type       what it is about
     * @param text       free text
     * @param observedOn day it refers to
     * @param today      today's date, so a note cannot be dated in the future
     * @param now        instant it is stored
     * @return the note
     * @throws IllegalArgumentException if the day is in the future
     */
    public static FieldNote record(FieldNoteId id, PlotId plotId, ProducerId producerId, FieldNoteType type,
            FieldNoteText text, LocalDate observedOn, LocalDate today, Instant now) {
        if (observedOn == null || today == null || observedOn.isAfter(today)) {
            throw new IllegalArgumentException("orchard.field_note.observed_on.future");
        }
        return new FieldNote(new FieldNoteSnapshot(id, plotId, producerId, type, text, observedOn, now, null));
    }

    /**
     * Attaches a photo, replacing the previous one if any.
     *
     * @param photo the photo
     * @return the note with the photo
     */
    public FieldNote attachPhoto(FieldNotePhoto photo) {
        if (photo == null) {
            throw new IllegalArgumentException("orchard.field_note.photo.empty");
        }
        var s = snapshot;
        return new FieldNote(new FieldNoteSnapshot(s.id(), s.plotId(), s.producerId(), s.type(), s.text(),
                s.observedOn(), s.recordedAt(), photo.mediaType()));
    }

    /**
     * Whether a resent note says the same as this one, so it can be answered as already stored.
     *
     * @param plotId     plot of the resent note
     * @param type       its type
     * @param text       its text
     * @param observedOn its day
     * @return true if nothing differs
     */
    public boolean sameAs(PlotId plotId, FieldNoteType type, FieldNoteText text, LocalDate observedOn) {
        return snapshot.plotId().equals(plotId) && snapshot.type() == type && snapshot.text().equals(text)
                && snapshot.observedOn().equals(observedOn);
    }

    public FieldNoteSnapshot snapshot() {
        return snapshot;
    }
}

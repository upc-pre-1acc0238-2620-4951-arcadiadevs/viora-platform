package com.arcadiadevs.viora.platform.orchard.domain.model.aggregates;

import com.arcadiadevs.viora.platform.orchard.domain.model.valueobjects.FieldNoteId;
import com.arcadiadevs.viora.platform.orchard.domain.model.valueobjects.FieldNoteText;
import com.arcadiadevs.viora.platform.orchard.domain.model.valueobjects.FieldNoteType;
import com.arcadiadevs.viora.platform.orchard.domain.model.valueobjects.PlotId;
import com.arcadiadevs.viora.platform.orchard.domain.model.valueobjects.ProducerId;

import java.time.Instant;
import java.time.LocalDate;

/**
 * State of a field note. The photo bytes are kept apart, so listing notes never loads them.
 *
 * @param id             note identity, generated by the phone
 * @param plotId         plot the note is about
 * @param producerId     owner of the plot who wrote it
 * @param type           what the note is about
 * @param text           free text
 * @param observedOn     day the producer saw or did what the note says
 * @param recordedAt     instant the server stored it
 * @param photoMediaType media type of the attached photo, null without photo
 */
public record FieldNoteSnapshot(
        FieldNoteId id,
        PlotId plotId,
        ProducerId producerId,
        FieldNoteType type,
        FieldNoteText text,
        LocalDate observedOn,
        Instant recordedAt,
        String photoMediaType
) {

    public FieldNoteSnapshot {
        if (id == null || plotId == null || producerId == null || type == null || text == null
                || observedOn == null || recordedAt == null) {
            throw new IllegalArgumentException("orchard.field_note.content.invalid");
        }
    }

    public boolean hasPhoto() {
        return photoMediaType != null;
    }
}

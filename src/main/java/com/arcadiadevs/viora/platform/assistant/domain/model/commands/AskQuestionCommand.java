package com.arcadiadevs.viora.platform.assistant.domain.model.commands;

import com.arcadiadevs.viora.platform.assistant.domain.model.valueobjects.PlotId;
import com.arcadiadevs.viora.platform.assistant.domain.model.valueobjects.QuestionId;
import com.arcadiadevs.viora.platform.assistant.domain.model.valueobjects.ScreenKey;
import com.arcadiadevs.viora.platform.assistant.domain.services.QuestionCatalog;

import java.util.Locale;
import java.util.UUID;

/**
 * Command asking the assistant one closed question about a plot, or about the producer's whole field on a screen
 * with field scope (HOME).
 *
 * @param producerId      producer asking, whose plan must be active
 * @param questionId      question of the catalog
 * @param plotId          plot the question is about; null only for a question of a screen with field scope
 * @param clientRequestId idempotency key generated by the app
 * @param forceRefresh    whether to skip the answers cached with the same data ("Volver a preguntar")
 * @param locale          language of the request
 */
public record AskQuestionCommand(
        String producerId,
        QuestionId questionId,
        PlotId plotId,
        UUID clientRequestId,
        boolean forceRefresh,
        Locale locale
) {

    public AskQuestionCommand {
        if (producerId == null || producerId.isBlank()) {
            throw new IllegalArgumentException("assistant.producer_id.null");
        }
        if (questionId == null) {
            throw new IllegalArgumentException("assistant.question.invalid");
        }
        if (plotId == null && QuestionCatalog.screenOf(questionId).map(ScreenKey::requiresPlot).orElse(true)) {
            throw new IllegalArgumentException("assistant.plot.required");
        }
        if (clientRequestId == null) {
            throw new IllegalArgumentException("assistant.client_request.invalid");
        }
        locale = locale == null ? Locale.ENGLISH : locale;
    }
}
